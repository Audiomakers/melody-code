#!/usr/bin/env python3
"""Prepares the piano used by the piano sets from Upright Piano KW (FreePats, CC0 1.0 public domain):
https://freepats.zenvoid.org/Piano/acoustic-grand-piano.html#UprightKW

Usage: build_piano.py <folder of the SFZ+FLAC release>
Each sample (two velocity layers, one every minor third) is cut to 5 s with a fade, saved as Ogg Vorbis in
Assets/Piano, and listed in Source/PianoTable.inc (layer, root key, resource name)."""
import os, re, subprocess, sys

src = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'Assets', 'Piano')
os.makedirs(out, exist_ok=True)
sfz = open(os.path.join(src, next(f for f in os.listdir(src) if f.endswith('.sfz')))).read()
rows = []
for g in sfz.split('<group>')[1:]:
    head = g.split('<region>')[0]
    layer = 0 if 'hivel=80' in head else 1
    for key, name in re.findall(r'pitch_keycenter=(\d+).*?sample=samples/(\S+)\.flac', g, re.S):
        key = int(key)
        if not 33 <= key <= 99: continue
        res = 'piano_%s' % name.replace('#', 's')
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', os.path.join(src, 'samples', name + '.flac'),
                        '-t', '5', '-af', 'afade=t=out:st=3.5:d=1.5', '-ar', '44100', '-c:a', 'libvorbis', '-q:a', '4',
                        os.path.join(out, res + '.ogg')], check=True)
        rows.append((layer, key, res))
with open(os.path.join(here, '..', 'Source', 'PianoTable.inc'), 'w') as f:
    f.write('// generated by tools/build_piano.py: velocity layer (0 soft, 1 hard), root key, resource\n')
    for layer, key, res in sorted(rows):
        f.write('{ %d, %d, "%s_ogg" },\n' % (layer, key, res))
with open(os.path.join(out, 'LICENSE.txt'), 'w') as f:
    f.write('Upright Piano KW, by Gonzalo and Roberto (FreePats project), recorded from a Kawai upright piano.\n'
            'https://freepats.zenvoid.org/Piano/acoustic-grand-piano.html#UprightKW\n'
            'Creative Commons CC0 1.0 public domain dedication: https://creativecommons.org/publicdomain/zero/1.0/\n')
print(len(rows), 'samples')
